import { fontVariableName } from "./font-names";
import { FONT_WEIGHTS } from "./font-specs";
import type { SemanticTokens, Theme, ThemeMode, ThemeTokens } from "./types";

/** Shared semantic colours per mode (design §5.2). */
export const SEMANTIC: Readonly<Record<ThemeMode, SemanticTokens>> = {
  light: {
    success: "#2F6B4F",
    successForeground: "#FFFFFF",
    warning: "#7A4A00",
    warningForeground: "#FFFFFF",
    destructive: "#A23B3B",
    destructiveForeground: "#FFFFFF",
  },
  dark: {
    success: "#8FD1AE",
    successForeground: "#0F2A1D",
    warning: "#F2C46D",
    warningForeground: "#2B1B00",
    destructive: "#F0A3A3",
    destructiveForeground: "#2A1010",
  },
};

export const RADIUS = "12px";

/** camelCase token name to the CSS custom property. */
export function cssVarName(token: string): string {
  return `--${token.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;
}

function block(selector: string, declarations: ReadonlyArray<readonly [string, string]>): string {
  const lines = declarations.map(([name, value]) => `  ${name}: ${value};`);
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

function tokenDeclarations(tokens: ThemeTokens, mode: ThemeMode): Array<[string, string]> {
  const all: Record<string, string> = {
    ...tokens,
    ring: tokens.primary,
    ...SEMANTIC[mode],
  };
  return [
    ["color-scheme", mode],
    ...Object.entries(all).map(([name, value]): [string, string] => [
      cssVarName(name),
      value.toLowerCase(),
    ]),
  ];
}

/**
 * Generates `src/app/themes.css`: one light and one dark block per theme, scoped by
 * `[data-theme]` / `[data-mode]` (never `:root`, so a gallery card can carry its own theme).
 */
export function generateThemesCss(themes: readonly Theme[]): string {
  const parts = [
    "/* GENERATED by `npm run gen:themes` from src/themes/catalog.ts. Do not edit by hand. */\n",
  ];
  for (const theme of themes) {
    parts.push(
      block(`[data-theme="${theme.id}"]`, [
        ["--font-heading", `var(${fontVariableName(theme.fonts.heading)}), Georgia, serif`],
        [
          "--font-body",
          `var(${fontVariableName(theme.fonts.body)}), ui-sans-serif, system-ui, sans-serif`,
        ],
        ["--font-heading-weight", FONT_WEIGHTS[theme.fonts.heading]?.[0] ?? "400"],
        ["--radius", RADIUS],
        ...tokenDeclarations(theme.light, "light"),
      ]),
      block(`[data-theme="${theme.id}"][data-mode="dark"]`, tokenDeclarations(theme.dark, "dark")),
    );
  }
  return parts.join("\n");
}
